    fragment = yaml.safe_load((site / OLIVETIN_FRAGMENT).read_text(encoding="utf-8"))
    deploy_ids = [a["id"] for a in fragment["actions"] if a["id"].startswith("stayturgid_deploy_")]
    assert deploy_ids == ["stayturgid_deploy_alpha", "stayturgid_deploy_mid", "stayturgid_deploy_zeta"]

    import json

