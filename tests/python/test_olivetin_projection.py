LIVE_HEADER = "# GENERATED by stayturgid site-sync — DO NOT EDIT (single-writer projection)\n# bootstrap placeholder\n"


def _init_site(tmp_path: Path, name: str = "example") -> Path:
    dest = tmp_path / f"site-{name}"
    err = io.StringIO()
    code = si.run_site_init(
        sitename=name,
        dir_path=str(dest),
        mode="apply",
        product_root=ROOT,
        env={},
        stdout=io.StringIO(),
        stderr=err,
    )
    assert code == si.EXIT_OK, err.getvalue()
    return dest


def _write_inventory(site: Path, host_names: list[str]) -> None:
    hosts = {
        name: {"ansible_host": f"100.0.0.{10 + index}", "device_label": f"Device {name}"}
        for index, name in enumerate(host_names)
    }
    doc = {"all": {"children": {"stayturgid": {"hosts": hosts}}}}
    (site / "inventory" / "hosts.yml").write_text(yaml.safe_dump(doc), encoding="utf-8")


def _enable_site_ns(site: Path, ns: str = "example") -> None:
    group_vars = site / "inventory" / "group_vars"
    group_vars.mkdir(parents=True, exist_ok=True)
    (group_vars / "all.yml").write_text(f"site_ns: {ns}\n", encoding="utf-8")


def _live_config_path(home: Path, ns: str = "example") -> Path:
    return home / ".config" / ns / "olivetin" / "config.yaml"


def _seed_live_config(home: Path, ns: str = "example", content: str | None = None) -> Path:
    live = _live_config_path(home, ns)
    live.parent.mkdir(parents=True, exist_ok=True)
    live.write_text(content if content is not None else LIVE_HEADER + "actions: []\n", encoding="utf-8")
    return live


def _sync(
    site: Path,
    home: Path,
    *,
    mode: str = "apply",
    commit: str = FIXED_COMMIT,
    manifest_path: Path | None = None,
) -> tuple[int, str, str]:
    out = io.StringIO()
    err = io.StringIO()
    code = ss.run_site_sync(
        dir_path=str(site),
        mode=mode,
        product_root=ROOT,
        env={},
        manifest_path=manifest_path,
        product_version=FIXED_VERSION,
        product_commit=commit,
        synced=FIXED_SYNCED,
        stdout=out,
        stderr=err,
        home=home,
    )
    return code, out.getvalue(), err.getvalue()


def _actions_map(stdout: str) -> dict[str, str]:
    actions: dict[str, str] = {}
    for line in stdout.splitlines():
        if not line.strip():
            continue
        parts = line.split(maxsplit=1)
        actions[parts[1]] = parts[0]
    return actions


def _snapshot_files(root: Path) -> dict[str, bytes]:
    if not root.exists():
        return {}
    return {p.relative_to(root).as_posix(): p.read_bytes() for p in sorted(root.rglob("*")) if p.is_file()}


# ── Purity ──────────────────────────────────────────────────────────────────


def test_pure_rerender_is_byte_identical_and_second_apply_noop(tmp_path: Path) -> None:
    site = _init_site(tmp_path)
    home = tmp_path / "home"
    _write_inventory(site, ["zeta", "alpha", "mid"])

    code, _, err = _sync(site, home)
    assert code == 0, err
    first = _snapshot_files(site / GENERATED)

    code, out, err = _sync(site, home, mode="dry-run")
    assert code == 0, err
    assert set(_actions_map(out).values()) == {"skip"}, out

    code, _, err = _sync(site, home)
    assert code == 0, err
    assert _snapshot_files(site / GENERATED) == first


def test_hosts_render_sorted_by_name_regardless_of_inventory_order(tmp_path: Path) -> None:
    site = _init_site(tmp_path)
    home = tmp_path / "home"
    _write_inventory(site, ["zeta", "alpha", "mid"])
    code, _, err = _sync(site, home)
