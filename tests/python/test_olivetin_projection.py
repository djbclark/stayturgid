# ── OliveTin single-writer merge ────────────────────────────────────────────


def test_projection_overwrites_live_config_and_writes_nothing_else(tmp_path: Path) -> None:
    site = _init_site(tmp_path)
    home = tmp_path / "home"
    _write_inventory(site, ["alpha"])
    _enable_site_ns(site)
    _seed_live_config(home)

    code, _, err = _sync(site, home)
    assert code == 0, err
    assert "olivetin projection: overwrite" in err

    live = _live_config_path(home)
    doc = yaml.safe_load(live.read_text(encoding="utf-8"))
    assert doc["ListenAddressSingleHTTPFrontend"] == "127.0.0.1:1337"
    assert doc["pageTitle"] == "Stayturgid Fleet Control"
    ids = [a["id"] for a in doc["actions"]]
    assert "stayturgid_fleet_health" in ids
    assert "stayturgid_deploy_alpha" in ids
    head = live.read_text(encoding="utf-8").splitlines()[:3]
    assert any("GENERATED by stayturgid" in line for line in head)
    # Single-writer write set: exactly the one live file under home.
    assert set(_snapshot_files(home)) == {live.relative_to(home).as_posix()}

    # Second apply: projection skip, live bytes unchanged.
    before = live.read_bytes()
    code, _, err = _sync(site, home)
    assert code == 0, err
    assert "olivetin projection: skip" in err
    assert live.read_bytes() == before


